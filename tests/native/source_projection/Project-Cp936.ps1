[CmdletBinding()]
param([Parameter(Mandatory)][string]$SourceRoot,[Parameter(Mandatory)][string]$RawRoot,[Parameter(Mandatory)][string]$OutputRoot)
$ErrorActionPreference='Stop'
function PlainPath([string]$Value){
  if(-not [IO.Path]::IsPathRooted($Value)){throw 'Projection paths must be absolute'}
  $full=[IO.Path]::GetFullPath($Value)
  for($cursor=$full;$cursor;$cursor=[IO.Path]::GetDirectoryName($cursor)){
    if(Test-Path -LiteralPath $cursor){if((Get-Item -LiteralPath $cursor -Force).Attributes-band[IO.FileAttributes]::ReparsePoint){throw 'Projection refuses reparse points'}}
  }
  return $full
}
function Hash([byte[]]$Bytes){$h=[Security.Cryptography.SHA256]::Create();try{return [BitConverter]::ToString($h.ComputeHash($Bytes)).Replace('-','').ToLowerInvariant()}finally{$h.Dispose()}}
function Relative([string]$Value){
  if([IO.Path]::IsPathRooted($Value)-or$Value-match'[\\:;\x00-\x1f]'-or$Value.Split('/')-contains'..'-or$Value.Split('/')-contains'.'){throw 'Unsafe projection member'}
  return $Value
}
function ClosedDirectory([string]$Directory,[Collections.Generic.HashSet[string]]$Allowed){
  if(-not(Test-Path -LiteralPath $Directory)){return}
  foreach($item in Get-ChildItem -LiteralPath $Directory -Recurse -Force){
    if($item.Attributes-band[IO.FileAttributes]::ReparsePoint){throw 'Projection directory contains a reparse point'}
    if(-not$item.PSIsContainer){$name=$item.FullName.Substring($Directory.Length+1).Replace('\','/');if(-not$Allowed.Contains($name)){throw "Unexpected projection member: $name"}}
  }
}
$SourceRoot=PlainPath $SourceRoot;$RawRoot=PlainPath $RawRoot;$OutputRoot=PlainPath $OutputRoot
if([IO.Path]::GetFileName($RawRoot)-cne'generated'-or[IO.Path]::GetFileName($OutputRoot)-cne'generated-utf8'-or
  [IO.Path]::GetDirectoryName($RawRoot)-cne[IO.Path]::GetDirectoryName($OutputRoot)){throw 'UTF8 projection must be the raw generated directory sibling'}
$bindingPath=Join-Path $RawRoot 'source-binding.json'
$bindingBytes=[IO.File]::ReadAllBytes($bindingPath)
$binding=[Text.UTF8Encoding]::new($false,$true).GetString($bindingBytes)|ConvertFrom-Json
if($binding.schema-notin@('window-close-lifetime-source/1','scheduler-continuation-contract/1')-or-not$binding.entries.Count){throw 'Unsupported raw source binding'}
if($PSVersionTable.PSEdition-eq'Core'){[Text.Encoding]::RegisterProvider([Text.CodePagesEncodingProvider]::Instance)}
$cp936=[Text.Encoding]::GetEncoding(936,[Text.EncoderExceptionFallback]::new(),[Text.DecoderExceptionFallback]::new())
$utf8=[Text.UTF8Encoding]::new($false,$true)
$rows=[Collections.Generic.List[object]]::new();$outputs=[Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach($entry in $binding.entries){
  $member=Relative $entry.target;$source=Relative $entry.source
  if($member-notmatch'\.(h|inc)$'-or-not$source.StartsWith('third_party/sources/miniblink/',[StringComparison]::Ordinal)-or-not$outputs.Add($member)){throw 'Unexpected or duplicate projection source'}
  $rawPath=PlainPath (Join-Path $RawRoot $member);$sourcePath=PlainPath (Join-Path $SourceRoot $source)
  $raw=[IO.File]::ReadAllBytes($rawPath);$whole=[IO.File]::ReadAllBytes($sourcePath)
  if((Hash $whole)-cne$entry.sourceSha256-or(Hash $raw)-cne$entry.fragmentSha256-or
    $entry.startByte-lt0-or$entry.endByteExclusive-gt$whole.Length-or$entry.endByteExclusive-$entry.startByte-ne$raw.Length){throw 'Raw projection source identity differs'}
  for($index=0;$index-lt$raw.Length;++$index){if($raw[$index]-ne$whole[$entry.startByte+$index]){throw 'Raw generated bytes differ from the bound production range'}}
  $text=$cp936.GetString($raw);$roundTrip=$cp936.GetBytes($text)
  if([Convert]::ToBase64String($raw)-cne[Convert]::ToBase64String($roundTrip)){throw 'CP936 projection does not round trip exactly'}
  $converted=$utf8.GetBytes($text)
  $rows.Add([ordered]@{target=$member;source=$source;startByte=$entry.startByte;endByteExclusive=$entry.endByteExclusive;
    rawBytes=$raw.Length;rawSha256=(Hash $raw);utf8Bytes=$converted.Length;utf8Sha256=(Hash $converted);roundTripExact=$true;content=$converted})
}
$rawAllowed=[Collections.Generic.HashSet[string]]::new($outputs,[StringComparer]::OrdinalIgnoreCase)
$projectedAllowed=[Collections.Generic.HashSet[string]]::new($outputs,[StringComparer]::OrdinalIgnoreCase)
$null=$rawAllowed.Add('source-binding.json');$null=$projectedAllowed.Add('projection.json')
ClosedDirectory $RawRoot $rawAllowed
ClosedDirectory $OutputRoot $projectedAllowed
New-Item -ItemType Directory -Force -Path $OutputRoot|Out-Null
foreach($row in $rows){
  $output=PlainPath (Join-Path $OutputRoot $row.target)
  New-Item -ItemType Directory -Force -Path ([IO.Path]::GetDirectoryName($output))|Out-Null
  [IO.File]::WriteAllBytes($output,$row.content);$row.Remove('content')
}
$record=[ordered]@{schema='soui.test-source-utf8-projection/v1';encodingFrom='CP936';encodingTo='UTF-8';
  rawBindingSha256=(Hash $bindingBytes);rawSourcesRetained=$true;entries=$rows.ToArray()}
[IO.File]::WriteAllText((Join-Path $OutputRoot 'projection.json'),($record|ConvertTo-Json -Depth 10),$utf8)
ClosedDirectory $OutputRoot $projectedAllowed

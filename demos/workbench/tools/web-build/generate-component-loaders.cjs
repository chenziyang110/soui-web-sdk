const fs = require('fs');
const path = require('path');
const ts = require('../../web/node_modules/typescript');
const root = path.resolve(__dirname, '../..');
const directory = path.join(root, 'web/apps/demo/src');
const sourcePath = path.join(directory, 'component-examples.ts');
const source = fs.readFileSync(sourcePath, 'utf8');
const ast = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const cases = new Map();
const catalogNames = [];
function visit(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(ast)==='catalog' && node.initializer && ts.isCallExpression(node.initializer)) {
    const expression = node.initializer.expression;
    if (ts.isPropertyAccessExpression(expression) && ts.isArrayLiteralExpression(expression.expression)) {
      for (const item of expression.expression.elements) {
        if (!ts.isArrayLiteralExpression(item) || !ts.isStringLiteral(item.elements[1])) throw Error('Catalog must contain literal names');
        catalogNames.push(item.elements[1].text);
      }
    }
  }
  if (ts.isSwitchStatement(node) && node.expression.getText(ast) === 'n') {
    const pending = [];
    for (const clause of node.caseBlock.clauses) {
      if (!ts.isCaseClause(clause) || !ts.isStringLiteral(clause.expression)) continue;
      pending.push(clause.expression.text);
      if (clause.statements.length) {
        const code = clause.statements.map(statement=>statement.getText(ast)).join('\n');
        for (const name of pending) cases.set(name,code);
        pending.length = 0;
      }
    }
  }
  ts.forEachChild(node,visit);
}
visit(ast);
if (cases.size !== 82) throw Error(`Expected all 82 component families, found ${cases.size}`);
if(catalogNames.length!==cases.size || catalogNames.some(name=>!cases.has(name))) throw Error('Catalog and examples differ');
const loaders = path.join(directory,'component-loaders');
const owners = new Map();
const upstream = fs.readFileSync(path.join(root,'web/node_modules/element-plus/es/component.mjs'),'utf8');
for (const match of upstream.matchAll(/import \{([^}]+)\} from '\.\/components\/([^/]+)\/index\.mjs'/g)) {
  for (const exported of match[1].split(',')) owners.set(exported.trim().replace(/^El/,''),match[2]);
}
fs.mkdirSync(loaders,{recursive:true});
const routes = [];
for (const [name,code] of cases) {
  if(!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw Error('Invalid component name');
  const required = new Set(['Button', name]);
  for (const match of code.matchAll(/\bc\('([A-Za-z0-9]+)'/g)) required.add(match[1]);
  for (const match of code.matchAll(/\bE\.El([A-Za-z0-9]+)/g)) required.add(match[1]);
  const imports = [], parts = [];
  let index = 0;
  const modules = new Set([...required].map(item=>owners.get(item) || item.replace(/([a-z0-9])([A-Z])/g,'$1-$2').toLowerCase()));
  for (const module of modules) {
    if(!/^[a-z][a-z0-9-]*$/.test(module)) throw Error('Invalid package module');
    const local = path.join(root,'web/node_modules/element-plus/es/components',module);
    if (!fs.existsSync(path.join(local,'index.mjs'))) throw Error(`No package module: ${module}`);
    imports.push(`import * as part${index} from 'element-plus/es/components/${module}/index';`);
    if (fs.existsSync(path.join(local,'style/css.mjs'))) imports.push(`import 'element-plus/es/components/${module}/style/css';`);
    parts.push(`...part${index++}`);
  }
  // Some child exports share their parent's JS module but have separate CSS
  // (ButtonGroup, FormItem, etc.). Preserve those styles as explicit dependencies.
  for (const item of required) {
    const style = 'el-' + item.replace(/([a-z0-9])([A-Z])/g,'$1-$2').toLowerCase() + '.css';
    if(fs.existsSync(path.join(root,'web/node_modules/element-plus/theme-chalk',style))) {
      imports.push(`import 'element-plus/theme-chalk/${style}';`);
    }
  }
  fs.writeFileSync(path.join(loaders,`${name}.ts`),`// Generated by tools/web-build/generate-component-loaders.cjs.\n${imports.join('\n')}\nexport default { ${parts.join(', ')} };\n`);
  routes.push(`  ${name}: () => import('./component-loaders/${name}'),`);
}
fs.writeFileSync(path.join(directory,'component-loaders.ts'),
  `// Generated finite map: local SystemJS chunks, never a remote URL.\nexport const componentLoaders: Record<string, () => Promise<{default: Record<string, unknown>}>> = {\n${routes.join('\n')}\n};\n`);
console.log(`Generated ${cases.size} explicit component loaders`);
